-- DB2 DDL and queries for the CUSTOMER table (matches cobol/copybooks/DCLCUST.cpy)

CREATE TABLE CUSTOMER (
    CUST_APP_NUMBER    CHAR(17)      NOT NULL WITH DEFAULT,
    CUST_STATUS        CHAR(15)      NOT NULL WITH DEFAULT,
    CUST_APP_DATE      DATE          NOT NULL WITH DEFAULT,
    CUST_FULL_NAME     VARCHAR(40)   NOT NULL WITH DEFAULT,
    CUST_FIRST_NAME    CHAR(20)      NOT NULL WITH DEFAULT,
    CUST_LAST_NAME     CHAR(20)      NOT NULL WITH DEFAULT,
    CUST_GENDER        CHAR(1)       NOT NULL WITH DEFAULT,
    CUST_EMIRATES_ID   CHAR(18)      NOT NULL WITH DEFAULT,
    CUST_DOB           DATE          NOT NULL WITH DEFAULT,
    CUST_NATIONALITY   CHAR(15),
    CUST_PHONE         CHAR(15),
    CUST_EMAIL         VARCHAR(40),
    CUST_CITY          CHAR(20),
    CUST_AMOUNT_DUE    DECIMAL(9, 2) NOT NULL WITH DEFAULT,
    PRIMARY KEY (CUST_APP_NUMBER)
);

-- Customers with a payment pending, dates as ISO text
SELECT CUST_APP_NUMBER,
       CHAR(CUST_APP_DATE, ISO)                  AS APP_DATE,
       SUBSTRING(CUST_EMIRATES_ID, 1, 3, OCTETS) AS ID_PREFIX,
       CHAR(CUST_AMOUNT_DUE)                     AS AMOUNT_DUE_TEXT
  FROM CUSTOMER
 WHERE CUST_STATUS = 'Pending Payment';

-- Applications per year (DKP-2026-538916-0 -> 2026)
SELECT SUBSTRING(CUST_APP_NUMBER, 5, 4, OCTETS) AS APP_YEAR,
       COUNT(*)                                 AS APPLICATIONS
  FROM CUSTOMER
 GROUP BY SUBSTRING(CUST_APP_NUMBER, 5, 4, OCTETS)
 ORDER BY APP_YEAR;
